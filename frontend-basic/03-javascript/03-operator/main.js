let productPrice = 30000;
let productCount = 2;
// 상품 가격과 수량을 저장

let addResult = productPrice + productCount;
console.log("덧셈:", addResult);
// 덧셈

let subtractResult = productPrice - productCount;
console.log("뺄셈:", subtractResult);
// 뺄셈

let multiplyResult = productPrice / productCount;
console.log("곱셈:", multiplyResult);

let divideResult = productPrice / productCount;
console.log("나눗셈:", divideResult);
// 나눗셈

let remainderResult = productPrice % productCount;
console.log("나머지:", remainderResult);


// 비교 연산자

let age = 30;

console.log(age > 20);
// 크다

console.log(age < 20);
// 작다

console.log(age >= 30);
// 크가나 같다

console.log(age <= 20);
// 작거나 같다

console.log(age === 30);
// 같다

console.log(age !== 20);

