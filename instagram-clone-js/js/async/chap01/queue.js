// 동기 코드는 콜스택에서 바로 실행
console.log('첫 번째 - 지금 바로');

// 2초 뒤 콜백을 태스크 큐에 넣음. 지금은 실행 안 함
setTimeout(() => {
  console.log('세 번째 - 대기 줄에 섰다가 마지막에');  
}, 2000);

// setTimeout은 예약만 하고 넘어오니까, 이것도 바로 실행
console.log('두 번째 - 이것도 지금 바로');

// 콜스택이 비고 2초가 지나야 큐에 있던 콜백이 실행됨
// 출력 순서: 첫 번째 → 두 번째 → (2초 후) 세 번째
